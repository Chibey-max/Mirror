import { readFile, rename, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const frontendRoot = resolve(import.meta.dirname, "..");
const repositoryRoot = resolve(frontendRoot, "..");
const chains = [46630, 421614];
const fields = ["agentRegistry", "trackRecord", "policyModule", "copyVault", "usdg"];
const addressPattern = /^0x[0-9a-fA-F]{40}$/;
const zero = /^0x0{40}$/i;

const addresses = {};
for (const chainId of chains) {
  const path = resolve(repositoryRoot, `deployments/${chainId}.json`);
  const manifest = JSON.parse(await readFile(path, "utf8"));
  if (manifest.schema !== "mirror.deployments.v1" || manifest.chainId !== chainId || !manifest.transactions) {
    throw new Error(`${path} is not a finalized Mirror deployment manifest`);
  }
  addresses[chainId] = {};
  for (const field of fields) {
    const value = manifest[field];
    if (typeof value !== "string" || !addressPattern.test(value) || zero.test(value)) {
      throw new Error(`${path} has invalid ${field}`);
    }
    addresses[chainId][field] = value;
  }
}

const source = `// Generated by scripts/sync-deployments.mjs. Do not edit by hand.\nexport const deployedAddresses = ${JSON.stringify(addresses, null, 2)} as const;\n`;
const target = resolve(frontendRoot, "lib/deployments.generated.ts");
const temporary = `${target}.tmp`;
await writeFile(temporary, source);
await rename(temporary, target);
process.stdout.write(`Updated ${target} from finalized deployment manifests\n`);
